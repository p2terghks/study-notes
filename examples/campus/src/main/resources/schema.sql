CREATE TABLE IF NOT EXISTS students (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_no VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(50) NOT NULL,
 password VARCHAR(100) NOT NULL, department VARCHAR(50) NOT NULL DEFAULT '컴퓨터공학과'
);
CREATE TABLE IF NOT EXISTS courses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, professor VARCHAR(50) NOT NULL,
 department VARCHAR(50) NOT NULL, category VARCHAR(20) NOT NULL,
 credits INT NOT NULL CHECK (credits > 0), capacity INT NOT NULL CHECK (capacity > 0),
 enrolled INT NOT NULL DEFAULT 0 CHECK (enrolled >= 0 AND enrolled <= capacity),
 room VARCHAR(50) NOT NULL, color VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS meetings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES courses(id), day_of_week INT NOT NULL CHECK(day_of_week BETWEEN 0 AND 4),
 start_minute INT NOT NULL, end_minute INT NOT NULL CHECK(end_minute > start_minute)
);
CREATE TABLE IF NOT EXISTS enrollments (
 student_id BIGINT NOT NULL REFERENCES students(id), course_id BIGINT NOT NULL REFERENCES courses(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(student_id, course_id)
);
CREATE TABLE IF NOT EXISTS cart (
 student_id BIGINT NOT NULL REFERENCES students(id), course_id BIGINT NOT NULL REFERENCES courses(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(student_id, course_id)
);

CREATE TABLE IF NOT EXISTS advising_profiles (
    student_id BIGINT PRIMARY KEY REFERENCES students(id),
    university VARCHAR(100) NOT NULL,
    admission_year INT NOT NULL CHECK (admission_year BETWEEN 1980 AND 2100)
);
